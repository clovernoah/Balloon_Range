/* ============================================================================
 * selftest.h —— 自检
 *
 * 全部是**不需要窗口、不需要 GL 上下文**的断言：数学、随机数、编码器、
 * 参数表、气球池、玩家相机。跑法：`bin\BalloonRange.exe --selftest`。
 *
 * 为什么这么设计：出图能证明"画面画出来了"，但证明不了"计分公式对不对"、
 * "打掉一个是不是真的立刻补一个"。这两件事得靠断言。而断言要能在没有显卡、
 * 没有桌面的环境里跑，所以逻辑层必须与渲染层彻底分家（见 player.h 的说明）。
 * ==========================================================================*/
#ifndef SELFTEST_H
#define SELFTEST_H

/* 跑完全部断言，返回**失败条数**（0 表示全绿）。
 * 详细报告写成 UTF-8 文本，路径写在 reportPath（可为 NULL）。*/
int selftestRun(const wchar_t *reportPath);

#endif /* SELFTEST_H */
