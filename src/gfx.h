/* ============================================================================
 * gfx.h —— 所有要碰 OpenGL 的 .cpp 都从这里进
 *
 * 把 "先 windows.h 再 GL/gl.h" 这个顺序要求收在一个地方。顺序错了
 * （比如某个文件先包含了 GL/gl.h）会报一堆看不懂的错，集中在这里最省事。
 * ==========================================================================*/
#ifndef GFX_H
#define GFX_H

#include "core.h"      /* 里面已经带了 windows.h 与 NOMINMAX */
#include <GL/gl.h>
#include <GL/glu.h>

/* ---------------------------------------------------------- 缺失的枚举常量
 * Windows SDK 自带的 GL/gl.h 只声明到 OpenGL 1.1，1.2 之后新增的枚举
 * 一个都没有。全程序用到的 1.2+ 枚举**只有 GL_CLAMP_TO_EDGE 这一个**
 * （贴图图集必须是 edge 夹取，不能 repeat），所以不引扩展加载器，直接把它
 * 补在这里 —— 值取自 OpenGL 官方 registry，是固定不变的。
 *
 * 为什么不用 GLEW 之类：本程序坚持零第三方依赖，而为了一个常量
 * 引入一整套扩展加载机制、外加一个函数指针加载失败面，不划算。
 * 真要用到 1.2 以上的**函数**时再考虑别的方案；真要用到别的常量，
 * 按上面同样的写法补一行即可（全程序没用到的 GL_BGRA 与
 * GL_MIRRORED_REPEAT 不在此列 —— 说"只用到一个"却补了两个是自相矛盾的，
 * 所以只留真正用到的）。*/
#ifndef GL_CLAMP_TO_EDGE
#define GL_CLAMP_TO_EDGE 0x812F
#endif

#endif /* GFX_H */
